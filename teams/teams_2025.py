# ============================================================
# 2024-25 TEAMS BUILT FROM BASKETBALL-REFERENCE (the hand-built teams above are unchanged)
# Ratings come from each player's real per-game, advanced and shooting numbers (the same stat-to-rating procedure as the
# 2025-26 teams), then calibrated by simulating full seasons. Minutes are the real per-game minutes scaled to 240.
# ============================================================
def _real_team(name, players, minutes):
    team = Team(name, players)
    for player, mpg in zip(players, minutes):
        player.real_mpg = mpg
    team.init_lineup()
    return team


