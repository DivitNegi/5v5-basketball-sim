def normalize_generated_team_roles(team: Team):
    top_tendency = max((p.shot_tendency for p in team.roster), default=0.0)
    depth_count = sum(1 for p in team.roster if p.shot_tendency >= 0.20)
    depth_factor = clamp((depth_count - 3) * 0.035, 0.0, 0.18)
    team.depth_scoring_factor = depth_factor

    for p in team.roster:
        p.team_depth_scoring_factor = depth_factor
        if p.shot_tendency >= top_tendency - 0.02:
            p.primary_scorer = True
        if p.shot_tendency >= 0.42:
            # Preserve manually-rated star volume instead of flattening every lead option.
            p.primary_scorer = True
            p.shot_tendency = clamp(p.shot_tendency + 0.005, 0.42, 0.58)
            p.usage = clamp(p.usage + 0.005, 0.18, 0.37)
        elif p.shot_tendency >= 0.30:
            p.shot_tendency = clamp(p.shot_tendency + 0.025 + depth_factor * 0.12, 0.16, 0.44)
            p.usage = clamp(p.usage + 0.012, 0.12, 0.28)
        elif p.shot_tendency >= 0.20:
            p.shot_tendency = clamp(p.shot_tendency + 0.030 + depth_factor * 0.10, 0.14, 0.34)
            p.usage = clamp(p.usage + 0.012, 0.10, 0.22)
        else:
            p.shot_tendency = clamp(p.shot_tendency + 0.010, 0.06, 0.22)


def make_2016_playoff_team(team_name: str) -> Team:
    if team_name == "2016 Cleveland Cavaliers":
        return _players_data().make_cavs_2016()
    if team_name == "2016 Golden State Warriors":
        return _players_data().make_warriors_2016()

    players = [build_2016_player(row) for row in PLAYOFF_2016_RATING_ROSTERS[team_name]]
    team = Team(team_name, players)
    normalize_generated_team_roles(team)
    team.init_lineup()
    team.seed = next(seed for conf in PLAYOFF_2016_STANDINGS.values() for name, seed, _, _ in conf if name == team_name)
    return team


