# ---- the other teams of 2022-23 (real Basketball-Reference data) ----
# Ratings derived from each player's real 2022-23 numbers and calibrated by full-season sims; rosters are the players who ended
# the season on the team. See ratings_2023.md.


def _real_team(name, players, minutes, defense_edge=1.0):
    team = Team(name, players)
    for player, mpg in zip(players, minutes):
        player.real_mpg = mpg
    team.defense_edge = defense_edge   # team defence modifier tuned to the real points allowed (players keep their own ratings)
    team.init_lineup()
    return team

