# ---- the other 25 teams of 2021-22 (real Basketball-Reference data) ----
# Every rating comes from the player's real 2021-22 numbers: each shot zone from its own efficiency (small samples shrink toward the
# middle), tendencies from his real shot mix, usage / playmaking / rebounding / steal / block from USG%, AST%, ORB%, DRB%, STL%, BLK%,
# defence from DBPM and role. They were then calibrated by simulating full 82-game seasons until each player's per-minute line matched
# the real one. `real_mpg` carries each player's real rotation minutes (scaled so a roster adds up to one game). See ratings_2022.md.


def _real_team(name, players, minutes):
    team = Team(name, players)
    for player, mpg in zip(players, minutes):
        player.real_mpg = mpg
    team.init_lineup()
    return team


